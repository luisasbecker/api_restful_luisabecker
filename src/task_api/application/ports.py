from collections.abc import Callable
from datetime import date, datetime
from typing import Protocol
from uuid import UUID

from task_api.domain.model import AuthSession, Comment, Priority, Task, TaskStatus, User


class Users(Protocol):
    def get(self, user_id: UUID, *, lock: bool = False) -> User | None: ...
    def by_email(self, email: str) -> User | None: ...
    def add(self, user: User) -> None: ...
    def save(self, user: User) -> None: ...
    def count_admins(self) -> int: ...
    def list_active(self, page: int, page_size: int) -> tuple[list[User], int]: ...


class Tasks(Protocol):
    def get(self, task_id: UUID, *, lock: bool = False) -> Task | None: ...
    def add(self, task: Task) -> None: ...
    def save(self, task: Task) -> None: ...
    def unassign_open(self, user_id: UUID, now: datetime) -> None: ...
    def list_visible(
        self,
        actor: User,
        assigned_to: UUID | None,
        status: TaskStatus | None,
        priority: Priority | None,
        due_before: date | None,
        page: int,
        page_size: int,
    ) -> tuple[list[Task], int]: ...


class Comments(Protocol):
    def get(self, comment_id: UUID) -> Comment | None: ...
    def add(self, comment: Comment) -> None: ...
    def save(self, comment: Comment) -> None: ...
    def list_for_task(
        self, task_id: UUID, page: int, page_size: int
    ) -> tuple[list[Comment], int]: ...


class Sessions(Protocol):
    def get(self, jti: UUID) -> AuthSession | None: ...
    def add(self, auth_session: AuthSession) -> None: ...
    def revoke(self, jti: UUID, now: datetime) -> None: ...
    def revoke_all(self, user_id: UUID, now: datetime) -> None: ...


class UnitOfWork(Protocol):
    users: Users
    tasks: Tasks
    comments: Comments
    sessions: Sessions

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *args: object) -> None: ...
    def lock_admins(self) -> None: ...
    def commit(self) -> None: ...


class Passwords(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


class Tokens(Protocol):
    def encode(self, user_id: UUID, jti: UUID, now: datetime, expires_at: datetime) -> str: ...
    def decode(self, token: str) -> tuple[UUID, UUID]: ...


UowFactory = Callable[[], UnitOfWork]
Clock = Callable[[], datetime]
